// Reply audit — markdown writers for docs/REPLY_AUDIT/.
import fs from 'node:fs'
import path from 'node:path'
import { cell, trunc } from './load.mjs'

const ROWS_PER_PART = 100

const table = (head, rows) => [
  `| ${head.join(' | ')} |`,
  `| ${head.map(() => '---').join(' | ')} |`,
  ...rows.map(r => `| ${r.map(cell).join(' | ')} |`),
].join('\n')

// ── S1 transcripts ────────────────────────────────────────────────────────
/** Packs whole scenes into parts of ~100 rows (a scene bigger than that gets its own part). */
function packParts(rows) {
  const byScene = []
  for (const r of rows) {
    if (byScene.at(-1)?.scene !== r.scene) byScene.push({ scene: r.scene, rows: [] })
    byScene.at(-1).rows.push(r)
  }
  const parts = [[]]
  for (const s of byScene) {
    if (parts.at(-1).length && parts.at(-1).length + s.rows.length > ROWS_PER_PART) parts.push([])
    parts.at(-1).push(...s.rows)
  }
  return parts.filter(p => p.length)
}

const TRANSCRIPT_HEAD = ['#', 'scene › list', 'choice id', 'choice text', 'gate', 'target', 'first 2 narrative nodes of target', 'choice reactions', 'flags set']

export function writeTranscripts(dir, rows) {
  const written = []
  for (let act = 1; act <= 7; act++) {
    const actRows = rows.filter(r => r.act === act).sort((a, b) => a.week - b.week || a.scene.localeCompare(b.scene))
    const parts = packParts(actRows)
    const partNames = parts.map((_, i) => `transcript-act${act}-p${String(i + 1).padStart(2, '0')}.md`)
    let n = 0
    parts.forEach((part, i) => {
      const body = part.map(r => [
        ++n, `${r.scene} › ${r.list}`, r.choice, r.text, r.gate || '—', r.target,
        r.first2.join(' ⏎ '), r.reactions.join(' ⏎ ') || '—', r.flags.join(', ') || '—',
      ])
      fs.writeFileSync(path.join(dir, partNames[i]), [
        `# Reply transcript — Act ${act}, part ${i + 1}/${parts.length}`,
        '',
        `Rows ${n - part.length + 1}–${n} of ${actRows.length}. Back to [index](transcript-act${act}.md). Columns per S1; ⏎ separates nodes/reactions; \`{if …}\` marks a per-node condition.`,
        '',
        table(TRANSCRIPT_HEAD, body),
        '',
      ].join('\n'))
    })
    const scenes = [...new Set(actRows.map(r => r.scene))]
    fs.writeFileSync(path.join(dir, `transcript-act${act}.md`), [
      `# Reply transcript — Act ${act}`,
      '',
      `${actRows.length} choice rows across ${scenes.length} scenes, split into ${parts.length} part file(s) of ~${ROWS_PER_PART} rows (whole scenes kept together).`,
      'Act bucket = `actN/` directory, else the scene\'s `act`, else its week.',
      '',
      ...partNames.map((p, i) => `- [${p}](${p}) — ${parts[i].length} rows, ${parts[i][0].scene} … ${parts[i].at(-1).scene}`),
      '',
    ].join('\n'))
    written.push({ act, rows: actRows.length, scenes: scenes.length, parts: parts.length })
  }
  return written
}

